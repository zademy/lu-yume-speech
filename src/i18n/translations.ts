const dictionaries: Record<AppLanguage, Dictionary> = { en, es };

/**
 * Translate a key for the given language, interpolating `{name}` params.
 * Falls back to English, then to the key itself.
 */
export function translate(
  lang: AppLanguage,
  key: string,
  params?: Record<string, string | number>,
): string {
  const raw = dictionaries[lang][key] ?? en[key] ?? key;
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (_match: string, name: string) => String(params[name] ?? ''));
}

/** Apply every `data-i18n[-placeholder|-aria-label|-title]` under `root`. */
export function translateTree(root: ParentNode, lang: AppLanguage): void {
  for (const el of root.querySelectorAll<HTMLElement>('[data-i18n]')) {
    const key = el.dataset.i18n;
    if (key) el.textContent = translate(lang, key);
  }
  for (const el of root.querySelectorAll<HTMLElement>('[data-i18n-placeholder]')) {
    const key = el.dataset.i18nPlaceholder;
    if (key && (el instanceof HTMLInputElement || el instanceof HTMLTextAreaElement)) {
      el.placeholder = translate(lang, key);
    }
  }
  for (const el of root.querySelectorAll<HTMLElement>('[data-i18n-aria-label]')) {
    const key = el.dataset.i18nAriaLabel;
    if (key) el.setAttribute('aria-label', translate(lang, key));
  }
  for (const el of root.querySelectorAll<HTMLElement>('[data-i18n-title]')) {
    const key = el.dataset.i18nTitle;
    if (key) el.setAttribute('title', translate(lang, key));
  }
}
